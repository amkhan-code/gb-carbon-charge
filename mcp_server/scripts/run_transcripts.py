"""Run real questions through a headless agent that can only use this MCP server, and record what happened.

    uv run python mcp_server/scripts/run_transcripts.py --db data/carbon.duckdb

For each question it starts `claude -p` with every built-in tool disabled and only this server registered, saves the
raw event stream (JSON lines) and renders a readable markdown transcript. Nothing is edited by hand; local paths are
replaced with placeholders before saving. It uses your Claude Code login, so it spends a little of your usage.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

SERVER = "gb-carbon-charge"
QUESTIONS = [
    ("01-model-vs-baseline", "Did the LightGBM carbon model beat the 'same period yesterday' baseline, and by how much? Is the difference reliable?"),
    ("02-date-outside-window", "How accurate were the carbon forecasts for 12 October 2026?"),
    ("03-clock-change-night", "On the night of 25 October 2025, when the clocks went back, when did each charging strategy charge, and how much carbon did the forecast-optimised plan save compared with the overnight timer?"),
    ("04-wind-experiment", "Did adding the NESO wind forecast improve the model? Be careful about which evaluation window you trust."),
]


def sanitise(text: str, repo: Path) -> str:
    for old, new in ((str(repo), "<repo>"), (str(Path.home()), "~"), (os.environ.get("USER", "\0"), "user")):
        text = text.replace(old, new)
    return re.sub(r"/Users/[^/\s\"]+", "~", text)


def run_one(question: str, db: Path, repo: Path, timeout: int = 420) -> list[dict]:
    cfg = {"mcpServers": {SERVER: {"command": sys.executable, "args": ["-m", "carbon_charge_mcp", "--db", str(db)]}}}
    with tempfile.TemporaryDirectory() as empty:  # an empty working directory: no project files, no CLAUDE.md
        cmd = ["claude", "-p", question, "--tools", "", "--mcp-config", json.dumps(cfg), "--strict-mcp-config",
               "--allowedTools", f"mcp__{SERVER}", "--output-format", "stream-json", "--verbose",
               "--no-session-persistence", "--disable-slash-commands"]
        out = subprocess.run(cmd, cwd=empty, capture_output=True, text=True, timeout=timeout)
    events = [json.loads(line) for line in out.stdout.splitlines() if line.strip().startswith("{")]
    if not events:
        raise RuntimeError(f"no events from claude (exit {out.returncode}): {out.stderr[:500]}")
    return events


def blocks(msg: dict):
    c = msg.get("message", {}).get("content", [])
    return [{"type": "text", "text": c}] if isinstance(c, str) else c


def render(question: str, events: list[dict], limit: int = 1800) -> str:
    lines = [f"### {question}", ""]
    names = {}
    for ev in events:
        if ev.get("type") == "assistant":
            for b in blocks(ev):
                if b["type"] == "text" and b["text"].strip():
                    lines += [f"**Agent:** {b['text'].strip()}", ""]
                elif b["type"] == "tool_use":
                    names[b["id"]] = b["name"].replace(f"mcp__{SERVER}__", "")
                    lines += [f"**Tool call:** `{names[b['id']]}`", "```json", json.dumps(b["input"], indent=2), "```", ""]
        elif ev.get("type") == "user":
            for b in blocks(ev):
                if b["type"] == "tool_result":
                    c = b["content"]
                    text = c if isinstance(c, str) else "\n".join(x.get("text", "") for x in c if isinstance(x, dict))
                    shown = text if len(text) <= limit else text[:limit] + f"\n... [{len(text) - limit:,} more characters in the raw transcript]"
                    tag = "Tool result (error)" if b.get("is_error") else "Tool result"
                    lines += [f"**{tag}:** `{names.get(b['tool_use_id'], '?')}` ({len(text):,} characters)", "```", shown, "```", ""]
    res = next((e for e in reversed(events) if e.get("type") == "result"), {})
    lines += [f"_{res.get('num_turns', '?')} turns, {res.get('duration_ms', 0) / 1000:.1f} s._", ""]
    return "\n".join(lines)


START, END = "<!-- TRANSCRIPTS:START -->", "<!-- TRANSCRIPTS:END -->"


def embed(out: Path, readme: Path) -> None:
    """Replace the marked block in the README with the saved transcripts (nothing is rewritten or summarised)."""
    parts = [p.read_text().rstrip() for p in sorted(out.glob("*.md"))]
    if not parts:
        raise SystemExit("no transcripts saved yet: run without --embed-only first")
    body = ("Each transcript is a real run: a headless Claude Code agent with every built-in tool disabled, so the MCP "
            "server was its only way to find anything out. The raw event streams are in `transcripts/*.jsonl`; local "
            "paths were replaced with placeholders. Generated by `scripts/run_transcripts.py`.\n\n" + "\n\n---\n\n".join(parts))
    text = readme.read_text()
    a, b = text.index(START) + len(START), text.index(END)
    readme.write_text(text[:a] + "\n" + body + "\n" + text[b:])
    print(f"embedded {len(parts)} transcripts into {readme}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="data/carbon.duckdb")
    ap.add_argument("--out", default="mcp_server/transcripts")
    ap.add_argument("--only", help="Run just the question whose id starts with this prefix, e.g. 02.")
    ap.add_argument("--embed", action="store_true", help="After running, put the transcripts into mcp_server/README.md.")
    ap.add_argument("--embed-only", action="store_true", help="Do not run anything; embed the transcripts already saved.")
    args = ap.parse_args()
    repo, out = Path.cwd().resolve(), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.embed_only:
        embed(out, Path("mcp_server/README.md"))
        return
    for slug, question in QUESTIONS:
        if args.only and not slug.startswith(args.only):
            continue
        print(f"running {slug} ...", flush=True)
        events = run_one(question, Path(args.db).resolve(), repo)
        (out / f"{slug}.jsonl").write_text("\n".join(sanitise(json.dumps(e), repo) for e in events) + "\n")
        clean = [json.loads(sanitise(json.dumps(e), repo)) for e in events]
        (out / f"{slug}.md").write_text(sanitise(render(question, clean), repo))
        init = next((e for e in clean if e.get("subtype") == "init"), {})
        print(f"  tools visible to the agent: {sorted(t for t in init.get('tools', []))}")
    if args.embed:
        embed(out, Path("mcp_server/README.md"))


if __name__ == "__main__":
    main()
